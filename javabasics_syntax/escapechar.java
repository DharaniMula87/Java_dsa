//Print escape characters
class escapechar
{
    public static void main(String[] args)
    {
        System.out.println("Hello\tWorld");  //tab space
        System.out.println("Java\nprogramming"); //next line
        System.out.println("\"Dharani\"");   //Printing the name in double quotes
        System.out.println("C:\\Dharani\\java\\programming");  //Without writing the double quotes we can print the slashes
    }
}