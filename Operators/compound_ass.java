//Compound assignment
public class compound_ass 
{
    public static void main(String[] args)
    {
        int a=12;
        System.out.println("a+=2 : "+(a+=2));
        System.out.println("a-=2 : "+(a-=2));
        System.out.println("a*=2 : "+(a*=2));
        System.out.println("a/=2 : "+(a/=2));
        System.out.println("a%=2 : "+(a%=2));
    }
}